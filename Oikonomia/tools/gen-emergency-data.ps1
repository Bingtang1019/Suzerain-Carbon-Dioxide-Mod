

param(
    [string]$Source = '',
    [string]$Out = ''
)
$ErrorActionPreference = 'Stop'
$root = Split-Path (Split-Path $PSScriptRoot -Parent) -Parent
if (-not $Source) { $Source = Join-Path $root 'dian.txt' }
if (-not $Out) { $Out = Join-Path $root 'Oikonomia\src\Oikonomia\EmergencyQuoteData.Generated.cs' }
if (-not (Test-Path $Source)) { throw "找不到紧急状态文档：$Source" }

$raw = Get-Content -LiteralPath $Source -Raw -Encoding UTF8
$json = ("{" + $raw + "}") | ConvertFrom-Json
if ($json.emergency_states.Count -lt 1) { throw "emergency_states 为空" }

function CsString([string]$s) {
    if ($null -eq $s) { $s = '' }
    $s = $s.Replace('\', '\\').Replace('"', '\"')
    $s = $s.Replace("`r", '\r').Replace("`n", '\n').Replace("`t", '\t')
    return '"' + $s + '"'
}

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('// <auto-generated> 由 tools/gen-emergency-data.ps1 从 dian.txt 生成；请勿手改。')
[void]$sb.AppendLine('using System.Collections.Generic;')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('namespace Oikonomia')
[void]$sb.AppendLine('{')
[void]$sb.AppendLine('    internal sealed class EmergencyQuoteGroup')
[void]$sb.AppendLine('    {')
[void]$sb.AppendLine('        internal string Id;')
[void]$sb.AppendLine('        internal string Name;')
[void]$sb.AppendLine('        internal string[] BannedTags;')
[void]$sb.AppendLine('        internal int Priority;')
[void]$sb.AppendLine('        internal BudgetQuote[] Quotes;')
[void]$sb.AppendLine('    }')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('    internal static class EmergencyQuoteData')
[void]$sb.AppendLine('    {')
[void]$sb.AppendLine('        internal static readonly EmergencyQuoteGroup[] Groups =')
[void]$sb.AppendLine('        {')
foreach ($g in $json.emergency_states) {
    [void]$sb.AppendLine('            new EmergencyQuoteGroup')
    [void]$sb.AppendLine('            {')
    [void]$sb.AppendLine('                Id = ' + (CsString $g.id) + ',')
    [void]$sb.AppendLine('                Name = ' + (CsString $g.name) + ',')
    $tags = @($g.banned_tags) | ForEach-Object { CsString ([string]$_) }
    [void]$sb.AppendLine('                BannedTags = new[] { ' + ($tags -join ', ') + ' },')
    [void]$sb.AppendLine('                Priority = ' + [int]$g.priority + ',')
    [void]$sb.AppendLine('                Quotes = new[]')
    [void]$sb.AppendLine('                {')
    foreach ($q in $g.quotes) {
        [void]$sb.AppendLine('                    new BudgetQuote { Text = ' + (CsString $q.text) + ', Author = ' + (CsString $q.author) + ', Source = ' + (CsString $q.source) + ' },')
    }
    [void]$sb.AppendLine('                }')
    [void]$sb.AppendLine('            },')
}
[void]$sb.AppendLine('        };')
[void]$sb.AppendLine('    }')
[void]$sb.AppendLine('}')
[IO.File]::WriteAllText($Out, $sb.ToString(), (New-Object Text.UTF8Encoding($false)))
Write-Host "生成：$Out（groups=$($json.emergency_states.Count)，quotes=$(($json.emergency_states | ForEach-Object { $_.quotes.Count } | Measure-Object -Sum).Sum)）"
