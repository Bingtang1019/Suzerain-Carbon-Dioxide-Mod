

param(
    [string]$Source = '',
    [string]$Out = ''
)
$ErrorActionPreference = 'Stop'
$root = Split-Path (Split-Path $PSScriptRoot -Parent) -Parent
if (-not $Source) { $Source = Join-Path $root '新建 文本文档.txt' }
if (-not $Out) { $Out = Join-Path $root 'Oikonomia\src\Oikonomia\BudgetQuoteData.Generated.cs' }
if (-not (Test-Path $Source)) { throw "找不到引文文档：$Source" }

$json = Get-Content -LiteralPath $Source -Raw -Encoding UTF8 | ConvertFrom-Json
if ($json.cells.Count -ne 16) { throw "cells 数量不是 16：$($json.cells.Count)" }

function CsString([string]$s) {
    if ($null -eq $s) { $s = '' }
    $s = $s.Replace('\', '\\').Replace('"', '\"')
    $s = $s.Replace("`r", '\r').Replace("`n", '\n').Replace("`t", '\t')
    return '"' + $s + '"'
}

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('// <auto-generated> 由 tools/gen-quote-data.ps1 从 新建 文本文档.txt 生成；请勿手改。')
[void]$sb.AppendLine('using System.Collections.Generic;')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('namespace Oikonomia')
[void]$sb.AppendLine('{')
[void]$sb.AppendLine('    internal static class BudgetQuoteData')
[void]$sb.AppendLine('    {')
[void]$sb.AppendLine('        internal static readonly Dictionary<string, BudgetQuote[]> Cells =')
[void]$sb.AppendLine('            new Dictionary<string, BudgetQuote[]>')
[void]$sb.AppendLine('        {')
foreach ($cell in $json.cells) {
    $id = "$($cell.x)_$($cell.y)"
    [void]$sb.AppendLine('            { ' + (CsString $id) + ', new[]')
    [void]$sb.AppendLine('                {')
    foreach ($q in $cell.quotes) {
        [void]$sb.AppendLine('                    new BudgetQuote { Text = ' + (CsString $q.text) + ', Author = ' + (CsString $q.author) + ', Source = ' + (CsString $q.source) + ' },')
    }
    [void]$sb.AppendLine('                } },')
}
[void]$sb.AppendLine('        };')
[void]$sb.AppendLine('    }')
[void]$sb.AppendLine('}')
[IO.File]::WriteAllText($Out, $sb.ToString(), (New-Object Text.UTF8Encoding($false)))
Write-Host "生成：$Out（cells=$($json.cells.Count)，quotes=$(($json.cells | ForEach-Object { $_.quotes.Count } | Measure-Object -Sum).Sum)）"
